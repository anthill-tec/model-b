from tests.test_project_permission_policy import sha256_text as _sha256
from tests.test_raw_runner_guard import GUARDED_ROOTS

REPO_ROOT = Path(__file__).resolve().parent.parent
SOURCE = REPO_ROOT / "workflows-src"
WHEEL_PREFIX = "modelb_axi/_assets/workflows-src"
#: §S2 — the three files ``render`` returns, keyed by project-relative path.
RELEASE_YML = ".github/workflows/release.yml"
STAMP = ".github/scripts/stamp_version.py"
SECTION = ".github/scripts/changelog_section.py"
RENDERED_FILES = (RELEASE_YML, STAMP, SECTION)
#: §S2/§S3 — the two scripts' sources under ``workflows-src/``, by rendered path.
SCRIPT_SOURCES = {STAMP: "stamp_version.py", SECTION: "changelog_section.py"}
#: §S2 — the marker line, minus its sha256 hex.
MARKER_PREFIX = "# generated by modelb-axi (Model B release workflow); sha256 "
#: Inputs every render below uses unless a test says otherwise.
STACKS = ["python"]
TARGETS = ["pypi", "npm:pkg", "github-assets"]


def workflows_module():
    """``modelb_axi.workflows``, imported at call time so its absence fails each test alone."""
    return importlib.import_module("modelb_axi.workflows")


def render_files(stacks: list[str], targets: list[str], source_dir: Path = SOURCE) -> dict:
    """``workflows.render(stacks, targets, source_dir)``."""
    return workflows_module().render(stacks, targets, source_dir)


def marker_split(text: str) -> tuple[str, str]:
    """``(first line, the rest)`` — the rest being everything after the first newline."""
    first, _sep, rest = text.partition("\n")
    return first, rest


def _source_files() -> dict[str, bytes]:
    """Every file under ``workflows-src/`` (bytecode caches aside), by relative POSIX path."""
    return {path.relative_to(SOURCE).as_posix(): path.read_bytes()
            for path in sorted(SOURCE.rglob("*"))
            if path.is_file() and "__pycache__" not in path.parts}


def tearDownModule():
    # The artifacts are tests.test_package_publishing's, cached on that module: remove the build
    # and drop the cache, so that module rebuilds rather than reading a removed directory.
    publishing.tearDownModule()
    publishing._BUILD_ROOT = None


