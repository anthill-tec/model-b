"""The release-workflow templates, their renderer and ownership by first-line marker
(CR-MDB-068 §S2).

Contract: ``docs/changes/CR-MDB-068-release-and-ci-workflow-templates.md`` §S2.

Class map:

- ``WorkflowsSourceRootTest`` — ``workflows-src/`` is an asset root holding both §S3 scripts:
  force-included into the wheel as ``modelb_axi/_assets/workflows-src``, listed in the sdist's
  ``only-include`` and in ``[tool.uv] cache-keys``, and outside the raw-runner guard's roots.
- ``WorkflowsSourceShipsTest`` — every file under ``workflows-src/`` ships, byte for byte, in the
  sdist and in the wheel built from that sdist (REAL artifacts, ``tests.test_package_publishing``).
- ``WorkflowSourcesResolutionTest`` — ``scaffold._workflow_sources(home)`` resolves by
  ``_agent_sources``'s chain: ``install.toml``'s ``asset_root``, then ``default_asset_root()``.
- ``RenderContractTest`` — ``workflows.render(stacks, targets, source_dir)`` returns exactly the
  three files, deterministically, each under its marker; the scripts are their sources verbatim.
- ``RenderReadsOnlySourceDirTest`` — ``render`` reads ``source_dir`` and nothing else.
- ``FirstLineOwnershipTest`` — ``agents.first_line_ownership(text, prefix)`` classifies intact,
  hand-modified and unmanaged text, and ``place_owned`` applies it.
- ``PermissionPolicyUsesFirstLineOwnershipTest`` — the permission policy classifies through it, and
  ``_sha256_text`` (and ``first_line_ownership``) is defined once, in ``modelb_axi/agents.py``.

Stdlib only.
"""

import ast
