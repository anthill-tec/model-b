class RenderContractTest(unittest.TestCase):
    """§S2 — what ``render`` returns."""

    def test_render_returns_exactly_the_three_files(self):
        self.assertEqual(sorted(render_files(STACKS, TARGETS)), sorted(RENDERED_FILES))

    def test_render_is_deterministic(self):
        for stacks, targets in ((STACKS, TARGETS), (["bun", "rust"], []),
                                (["arduino"], ["github-assets"])):
            with self.subTest(stacks=stacks, targets=targets):
                first = render_files(stacks, targets)
                self.assertEqual(render_files(list(stacks), list(targets)), first)

    def test_each_files_first_line_is_the_marker_over_the_rest(self):
        for stacks, targets in ((STACKS, TARGETS), (["quarkus"], [])):
            for rel, text in render_files(stacks, targets).items():
                with self.subTest(stacks=stacks, targets=targets, file=rel):
                    first, rest = marker_split(text)
                    self.assertEqual(first, f"{MARKER_PREFIX}{_sha256(rest)}")
                    self.assertTrue(rest.strip(), "§S2: a body follows the marker")

    def test_the_marker_prefix_is_exposed_by_the_renderer(self):
        self.assertEqual(workflows_module().MARKER_PREFIX, MARKER_PREFIX)

    def test_each_script_is_its_source_verbatim_under_the_marker(self):
        files = render_files(STACKS, TARGETS)
        for rel, name in SCRIPT_SOURCES.items():
            with self.subTest(file=rel):
                self.assertEqual(marker_split(files[rel])[1],
                                 (SOURCE / name).read_text(encoding="utf-8"))

    def test_the_scripts_do_not_vary_with_the_stacks_or_targets(self):
        one, other = render_files(STACKS, TARGETS), render_files(["arduino", "java"], [])
        for rel in SCRIPT_SOURCES:
            with self.subTest(file=rel):
                self.assertEqual(one[rel], other[rel])
        self.assertNotEqual(one[RELEASE_YML], other[RELEASE_YML],
                            "§S4: the workflow follows the stacks and targets")


class RenderReadsOnlySourceDirTest(unittest.TestCase):
    """§S2 — ``render`` reads ``source_dir`` only: a copy renders the same; a change to the copy
    shows in the output; an empty directory renders nothing; the working directory and the
    packaged asset root are never consulted."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="r68-render-"))
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.copy = self.tmp / "copy"
        shutil.copytree(SOURCE, self.copy, ignore=shutil.ignore_patterns("__pycache__"))

    def test_a_copy_renders_byte_for_byte_the_same(self):
        self.assertEqual(render_files(STACKS, TARGETS, self.copy), render_files(STACKS, TARGETS))

    def test_a_change_in_the_copy_shows_in_the_output(self):
        script = self.copy / SCRIPT_SOURCES[STAMP]
        script.write_text(script.read_text(encoding="utf-8") + "# probe r68\n", encoding="utf-8")
        rendered = render_files(STACKS, TARGETS, self.copy)[STAMP]
        self.assertTrue(rendered.endswith("# probe r68\n"))
        self.assertNotIn("# probe r68", render_files(STACKS, TARGETS)[STAMP])

    def test_an_empty_source_dir_is_refused_not_filled_from_elsewhere(self):
        empty = self.tmp / "empty"
        empty.mkdir()
        with self.assertRaises((OSError, ValueError)):
            render_files(STACKS, TARGETS, empty)

    def test_neither_the_working_directory_nor_the_packaged_root_is_read(self):
        expected = render_files(STACKS, TARGETS)
        elsewhere = self.tmp / "cwd"
        elsewhere.mkdir()
        saved = os.getcwd()
        bogus = self.tmp / "no-such-asset-root"
        try:
            os.chdir(elsewhere)
            with mock.patch.object(deploy, "default_asset_root", return_value=bogus):
                got = render_files(STACKS, TARGETS, self.copy)
        finally:
            os.chdir(saved)
        self.assertEqual(got, expected)


# ------------------------------------------------------------------ ownership ----

def _owned(body: str, prefix: str = MARKER_PREFIX, newline: str = "\n") -> str:
    return f"{prefix}{_sha256(body)}{newline}{body}"


class FirstLineOwnershipTest(unittest.TestCase):
    """§S2 — ``agents.first_line_ownership(text, prefix)``: ``intact`` when the first line is
    ``prefix`` + the sha256 of the rest, ``hand_modified`` when the prefix is there and the digest
    is not, ``unmanaged`` otherwise."""

    BODY = "name: release\n\njobs:\n  test-python:\n    runs-on: ubuntu-latest\n"

    def _classify(self, text: str, prefix: str = MARKER_PREFIX) -> str:
        return agents.first_line_ownership(text, prefix)

    def test_an_intact_file_is_intact(self):
        self.assertEqual(self._classify(_owned(self.BODY)), agents.OWNED_INTACT)

    def test_a_crlf_marker_line_is_still_intact(self):
        self.assertEqual(self._classify(_owned(self.BODY, newline="\r\n")), agents.OWNED_INTACT)

    def test_an_edited_body_or_a_wrong_digest_is_hand_modified(self):
        for text in (_owned(self.BODY) + "# edited\n",
                     f"{MARKER_PREFIX}{'0' * 64}\n{self.BODY}"):
            with self.subTest(text=text[:80]):
                self.assertEqual(self._classify(text), agents.OWNED_HAND_MODIFIED)

    def test_no_marker_on_the_first_line_is_unmanaged(self):
        for text in (self.BODY, "", "# a comment\n" + _owned(self.BODY),
                     _owned(self.BODY, prefix=agents.MARKER_PREFIX)):
            with self.subTest(text=text[:80]):
                self.assertEqual(self._classify(text), agents.NOT_OWNED)

    def test_the_rendered_workflow_files_are_intact_under_the_workflow_prefix(self):
        for rel, text in render_files(STACKS, TARGETS).items():
            with self.subTest(file=rel):
                self.assertEqual(self._classify(text), agents.OWNED_INTACT)
                self.assertEqual(self._classify(text, permission_policy.MARKER_PREFIX),
                                 agents.NOT_OWNED)

    def test_place_owned_with_it_rewrites_skips_forces_and_leaves_unmanaged(self):
        tmp = Path(tempfile.mkdtemp(prefix="r68-own-"))
        self.addCleanup(shutil.rmtree, tmp, True)
        classify = functools.partial(agents.first_line_ownership, prefix=MARKER_PREFIX)
        new = _owned("name: release\n# v2\n")
        cases = (("intact", _owned(self.BODY), False, "written", new),
                 ("same", new, False, "unchanged", new),
                 ("hand", _owned(self.BODY) + "# edit\n", False, "skipped", None),
                 ("forced", _owned(self.BODY) + "# edit\n", True, "written", new),
                 ("unmarked", self.BODY, True, "unmanaged", None))
        for name, existing, force, bucket, after in cases:
            with self.subTest(case=name):
                path = tmp / name / "release.yml"
                path.parent.mkdir()
                path.write_text(existing, encoding="utf-8")
                report = {key: [] for key in ("written", "unchanged", "skipped", "unmanaged")}
                agents.place_owned(path, name, new, force, report, classify=classify)
                self.assertEqual({k: v for k, v in report.items() if v}, {bucket: [name]})
                self.assertEqual(path.read_text(encoding="utf-8"), after or existing)


class PermissionPolicyUsesFirstLineOwnershipTest(unittest.TestCase):
    """§S2 — the permission policy classifies through ``agents.first_line_ownership`` (its own
    copy goes), and ``_sha256_text`` is defined once."""

    def test_placing_the_policy_classifies_the_existing_file_through_it(self):
        tmp = Path(tempfile.mkdtemp(prefix="r68-policy-"))
        self.addCleanup(shutil.rmtree, tmp, True)
        permission_policy.place_project_policy(tmp, lean_ctx=False)
        existing = (tmp / permission_policy.PROJECT_POLICY_RELPATH).read_text(encoding="utf-8")
        real = agents.first_line_ownership
        with mock.patch.object(agents, "first_line_ownership", wraps=real) as spy:
            report = permission_policy.place_project_policy(tmp, lean_ctx=False)
        self.assertEqual(report["unchanged"], [str(permission_policy.PROJECT_POLICY_RELPATH)])
        self.assertEqual(spy.call_count, 1, "§S2: one classification of the one existing file")
        call = spy.call_args
        bound = inspect.signature(real).bind(*call.args, **call.kwargs)
        self.assertEqual(dict(bound.arguments),
                         {"text": existing, "prefix": permission_policy.MARKER_PREFIX})

    def test_sha256_text_and_first_line_ownership_are_defined_once_in_agents(self):
        package = REPO_ROOT / "modelb_axi"
        found: dict[str, list[str]] = {"_sha256_text": [], "first_line_ownership": []}
        for path in sorted(package.glob("*.py")):
            for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
                if isinstance(node, ast.FunctionDef) and node.name in found:
                    found[node.name].append(path.name)
        self.assertEqual(found, {"_sha256_text": ["agents.py"],
                                 "first_line_ownership": ["agents.py"]})


