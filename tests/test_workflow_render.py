class WorkflowsSourceRootTest(unittest.TestCase):
    """§S2 — ``workflows-src/`` is a packaged asset root, outside the raw-runner guard."""

    def _build(self) -> dict:
        return publishing._pyproject().get("tool", {})

    def test_the_root_holds_both_scripts(self):
        for name in SCRIPT_SOURCES.values():
            with self.subTest(script=name):
                self.assertTrue((SOURCE / name).is_file(), f"§S2: workflows-src/{name}")

    def test_the_wheel_force_includes_it_under_the_package_assets(self):
        force = (self._build().get("hatch", {}).get("build", {}).get("targets", {})
                 .get("wheel", {}).get("force-include", {}))
        self.assertEqual(force.get("workflows-src"), WHEEL_PREFIX, f"§S2: got {force!r}")

    def test_the_sdist_only_include_lists_it(self):
        only = (self._build().get("hatch", {}).get("build", {}).get("targets", {})
                .get("sdist", {}).get("only-include", []))
        self.assertIn("workflows-src", only, f"§S2: got {only!r}")

    def test_the_uv_cache_keys_list_it(self):
        keys = self._build().get("uv", {}).get("cache-keys", [])
        self.assertIn({"file": "workflows-src/**"}, keys, f"§S2: got {keys!r}")

    def test_it_is_an_existing_root_outside_the_raw_runner_guard(self):
        self.assertTrue(SOURCE.is_dir(), "§S2: workflows-src/ exists")
        self.assertEqual([root for root in GUARDED_ROOTS
                          if root == "workflows-src" or root.startswith("workflows-src/")], [],
                         "§S2: a workflow template shows each stack's test command")


class WorkflowsSourceShipsTest(unittest.TestCase):
    """§S2 AC — ``workflows-src/`` ships in the wheel built from the sdist."""

    @classmethod
    def setUpClass(cls):
        cls.sdist, cls.wheel = publishing.artifacts()

    def _sources(self) -> dict[str, bytes]:
        files = _source_files() if SOURCE.is_dir() else {}
        missing = [name for name in SCRIPT_SOURCES.values() if name not in files]
        self.assertEqual(missing, [], "precondition: workflows-src/ holds both scripts")
        return files

    def test_the_sdist_carries_every_file_byte_for_byte(self):
        members = publishing.sdist_members(self.sdist)
        for rel, data in self._sources().items():
            with self.subTest(file=rel):
                self.assertIn(f"workflows-src/{rel}", members)
                self.assertEqual(publishing.sdist_read(self.sdist, f"workflows-src/{rel}"), data)

    def test_the_wheel_carries_every_file_under_the_package_assets(self):
        names = set(publishing.wheel_names(self.wheel))
        for rel, data in self._sources().items():
            with self.subTest(file=rel):
                self.assertIn(f"{WHEEL_PREFIX}/{rel}", names)
                self.assertEqual(publishing.wheel_read(self.wheel, f"{WHEEL_PREFIX}/{rel}"), data)

    def test_the_wheel_carries_no_workflows_src_outside_the_package_assets(self):
        self._sources()
        stray = [name for name in publishing.wheel_names(self.wheel)
                 if "workflows-src" in name.split("/") and not name.startswith(WHEEL_PREFIX + "/")]
        self.assertEqual(stray, [])


