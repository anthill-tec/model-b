class WorkflowSourcesResolutionTest(unittest.TestCase):
    """§S2 — ``scaffold._workflow_sources(home)``: ``install.toml``'s ``asset_root`` first, then
    ``default_asset_root()``; the ``workflows-src`` directory of the first root holding one."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="r68-sources-"))
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.home = self.tmp / "home"
        self.home.mkdir()

    def _root(self, name: str, *, with_source: bool) -> Path:
        root = self.tmp / name
        root.mkdir()
        if with_source:
            (root / "workflows-src").mkdir()
        return root

    def _configure(self, asset_root: Path) -> None:
        (self.home / "install.toml").write_text(
            f'[install]\nharnesses = ["pi"]\nasset_root = "{asset_root}"\n', encoding="utf-8")

    def _resolve(self, fallback: Path) -> Path:
        with (mock.patch.object(scaffold, "default_asset_root", return_value=fallback),
              mock.patch.object(deploy, "default_asset_root", return_value=fallback)):
            return Path(scaffold._workflow_sources(self.home))

    def test_the_installed_asset_root_wins(self):
        configured = self._root("configured", with_source=True)
        self._configure(configured)
        fallback = self._root("fallback", with_source=True)
        self.assertEqual(self._resolve(fallback), configured / "workflows-src")

    def test_an_asset_root_without_workflows_src_falls_back_to_the_default(self):
        self._configure(self._root("configured", with_source=False))
        fallback = self._root("fallback", with_source=True)
        self.assertEqual(self._resolve(fallback), fallback / "workflows-src")

    def test_no_install_toml_uses_the_default(self):
        fallback = self._root("fallback", with_source=True)
        self.assertEqual(self._resolve(fallback), fallback / "workflows-src")

    def test_no_root_holding_workflows_src_is_a_scaffold_error_naming_it(self):
        self._configure(self._root("configured", with_source=False))
        with self.assertRaises(scaffold.ScaffoldError) as caught:
            self._resolve(self._root("fallback", with_source=False))
        self.assertIn("workflows-src", str(caught.exception))

    def test_the_repository_checkout_resolves_to_its_own_workflows_src(self):
        resolved = Path(scaffold._workflow_sources(self.home))
        self.assertEqual(resolved.resolve(), deploy.default_asset_root().resolve() / "workflows-src")
        self.assertTrue(resolved.is_dir())


