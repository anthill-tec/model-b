class InitStackSkillOwnershipTest(_StackSkillSandbox):
    """§S1.3 / AC1 — ``init`` over existing files: a hand-modified rendered file is skipped and
    reported; an unmarked file at a rendered path is left untouched and reported."""

    def test_init_skips_hand_modified_and_leaves_unmarked_untouched(self):
        target = self.root / "proj"
        hand_modified = with_skill_marker(
            FIXTURE_SOURCES["alpha-stack"]["SKILL.md"], "0" * 64
        )
        unmarked = "# My own alpha notes\n\nWritten by hand, no marker.\n"
        for path, text in ((ALPHA_SKILL, hand_modified), (ALPHA_NOTES, unmarked)):
            (target / path).parent.mkdir(parents=True, exist_ok=True)
            (target / path).write_text(text, encoding="utf-8")
        before = snapshot(target, (ALPHA_SKILL, ALPHA_NOTES))

        axi = self.init_ok(target, "rust")

        self.assertEqual(
            snapshot(target, (ALPHA_SKILL, ALPHA_NOTES)),
            before,
            "§S1.3: neither file is written",
        )
        self.assertIn(
            ALPHA_SKILL,
            _listed(axi, "skipped"),
            f"§S1.3: a hand-modified rendered file is skipped and reported; axi={axi!r}",
        )
        self.assertIn(
            ALPHA_NOTES,
            _listed(axi, "unmanaged"),
            f"§S1.3: an unmarked file at a rendered path is reported; axi={axi!r}",
        )
        emitted = _listed(axi, "emitted")
        self.assertNotIn(ALPHA_SKILL, emitted)
        self.assertNotIn(ALPHA_NOTES, emitted)
        self.assertIn(
            BETA_NOTES, emitted, "§S1.3: the other reference is still rendered"
        )
        warnings = " ".join(_listed(axi, "warnings"))
        for path in (ALPHA_SKILL, ALPHA_NOTES):
            self.assertIn(path, warnings, f"§S1.3: init reports {path} in its warnings")


