class AgentsVerbStackSkillsTest(_StackSkillSandbox):
    """§S1.4 / AC1 / AC2 — ``modelb-axi agents`` at the project root re-renders the stack skills
    by the same rules, names them in its envelope, is idempotent and never deletes."""

    def setUp(self):
        super().setUp()
        self.target = self.root / "proj"
        self.init_ok(self.target, "rust")

    def test_agents_rerenders_a_changed_source_and_names_it_written(self):
        source = self.source("alpha-stack", "SKILL.md")
        changed = (
            source.read_text(encoding="utf-8")
            + "\nA line the re-render must pick up.\n"
        )
        source.write_text(changed, encoding="utf-8")

        axi = self.agents_ok(self.target)

        rendered = self.target / ALPHA_SKILL
        self.assertTrue(rendered.is_file(), f"§S1.4: {ALPHA_SKILL} is re-rendered")
        text = rendered.read_text(encoding="utf-8")
        marker = next(
            (ln for ln in text.splitlines() if ln.startswith(SKILL_MARKER_PREFIX)), ""
        )
        self.assertEqual(
            text.replace(marker + "\n", "", 1),
            changed,
            "§S1.4: the re-render picks up the changed source",
        )
        written = _listed(axi, "written")
        self.assertIn(
            ALPHA_SKILL, written, f"§S1.4/AC2: named in the envelope; axi={axi!r}"
        )
        for ref in (ALPHA_NOTES, BETA_NOTES):
            self.assertIn(
                ref,
                _listed(axi, "unchanged"),
                f"§S1.4: an untouched reference is reported unchanged; axi={axi!r}",
            )
            self.assertNotIn(ref, written)

    def test_a_second_agents_run_changes_nothing(self):
        expected = expected_skill_files(["rust"])
        self.agents_ok(self.target)
        first = snapshot(self.target, expected)
        axi = self.agents_ok(self.target)
        self.assertEqual(sorted(first), expected, "AC2: the skill is rendered")
        self.assertEqual(
            snapshot(self.target, expected), first, "AC2: a second run changes nothing"
        )
        self.assertFalse(
            [p for p in _listed(axi, "written") if SKILLS_RELDIR in p],
            f"AC2: a second run writes no stack skill; axi={axi!r}",
        )
        unchanged = _listed(axi, "unchanged")
        for path in expected:
            self.assertIn(
                path,
                unchanged,
                f"§S1.4: an intact rendered file (either marker form) is unchanged; "
                f"axi={axi!r}",
            )

    def test_agents_after_the_project_drops_the_stack_deletes_nothing(self):
        expected = expected_skill_files(["rust"])
        before = snapshot(self.target, expected)
        self.assertEqual(
            sorted(before), expected, "precondition: init rendered the rust skill"
        )
        self.agents_ok(self.target, stacks="python")
        self.assertEqual(
            snapshot(self.target, expected),
            before,
            "§S1.4/AC2: a re-render never deletes a skill of a dropped stack",
        )

    def test_agents_skips_hand_modified_and_leaves_unmarked_untouched(self):
        notes = self.target / ALPHA_NOTES
        skill = self.target / ALPHA_SKILL
        self.assertTrue(
            notes.is_file() and skill.is_file(),
            "precondition: init rendered alpha-stack",
        )
        notes.write_text(
            notes.read_text(encoding="utf-8") + "A hand edit.\n", encoding="utf-8"
        )
        skill.write_text(
            "---\nname: alpha-stack\ndescription: mine\n---\n\nUnmarked.\n",
            encoding="utf-8",
        )
        before = snapshot(self.target, (ALPHA_NOTES, ALPHA_SKILL))

        axi = self.agents_ok(self.target)

        self.assertEqual(
            snapshot(self.target, (ALPHA_NOTES, ALPHA_SKILL)),
            before,
            "§S1.4: neither file is written",
        )
        self.assertIn(
            ALPHA_NOTES, _listed(axi, "skipped"), f"§S1.4: skipped; axi={axi!r}"
        )
        self.assertIn(
            ALPHA_SKILL, _listed(axi, "unmanaged"), f"§S1.4: unmanaged; axi={axi!r}"
        )
        self.assertIn(
            BETA_NOTES, _listed(axi, "unchanged"), f"§S1.4: unchanged; axi={axi!r}"
        )

