"""Stack skills: the mechanism (CR-MDB-085 §S1).

A stack skill's source is ``generator/skills/<name>/`` — a ``SKILL.md`` whose frontmatter
``name`` is the directory's name, and a ``references/`` directory only when it has references
(§S1.1). One declaration file, ``generator/stack-skills.toml``, names the stacks each skill
renders for; a stack with or without a stack file may be named, and a declared skill whose source
has no ``SKILL.md`` renders nothing (§S1.2). ``modelb-axi init`` renders the declared skill of each
stack in ``--stacks`` into ``.agents/skills/<name>/`` at the project root, under the agent
definitions' ownership rules and two pinned markers (§S1.3); ``modelb-axi agents`` re-renders
them, reports them in its envelope and never deletes (§S1.4). The rendered ``AGENTS.md`` stack
line names a stack's skill only where one is declared, and both trust surfaces name the stack
skills (§S1.5).

The declaration's shape, confirmed by the orchestrator for this cycle: one ``[skills.<name>]``
table per skill, carrying ``stacks = ["<stack>", …]``. It is written in one place,
:func:`declaration_text`.

Every rendering test drives a private asset root (``install.toml``'s ``asset_root``, the chain
the agent sources resolve through) holding SYNTHETIC skill sources, so nothing here depends on a
real skill's content: ``alpha-stack`` (rust, two references), ``ghost-stack`` (java, which has no
stack file; no references) and ``hollow-stack`` (arduino; a source with no ``SKILL.md``). The
expected rendering is derived from that data, so a fixture change is a data change.

Isolation: every run pins ``HOME``, ``PI_CODING_AGENT_DIR``, ``MODELB_HOME`` and
``XDG_DATA_HOME`` to a throw-away sandbox; the real installation is never read or written.

Stdlib only.
"""

