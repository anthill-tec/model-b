def stack_skill_source_findings(generator_dir: Path) -> list[str]:
    """§S1.1 / §S1.2 / AC1 — what breaks the source rules under ``generator_dir``: no declaration
    file; a declaration that does not parse, or a skill naming no stacks; a declared skill with no
    source directory, no ``SKILL.md``, or a frontmatter ``name`` other than its directory's; an
    empty ``references/``; a source directory no declaration names. An absent ``[skills]`` table
    declares no skill."""
    declaration = generator_dir / "stack-skills.toml"
    if not declaration.is_file():
        return [f"no declaration file {declaration.name}"]
    try:
        data = tomllib.loads(declaration.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as exc:
        return [f"{declaration.name} does not parse: {exc}"]
    skills = data.get("skills", {})
    if not isinstance(skills, dict):
        return [f"{declaration.name}: [skills] is not a table"]
    findings = []
    skills_dir = generator_dir / "skills"
    present = (
        {p.name for p in skills_dir.iterdir() if p.is_dir()}
        if skills_dir.is_dir()
        else set()
    )
    for name, entry in skills.items():
        stacks = entry.get("stacks") if isinstance(entry, dict) else None
        if not (
            isinstance(stacks, list)
            and stacks
            and all(isinstance(s, str) for s in stacks)
        ):
            findings.append(f"{name}: declares no stacks")
        if name not in present:
            findings.append(f"{name}: declared with no source directory")
            continue
        skill_md_path = skills_dir / name / "SKILL.md"
        if not skill_md_path.is_file():
            findings.append(f"{name}: source has no SKILL.md")
        else:
            frontmatter, _ = split_frontmatter(
                skill_md_path.read_text(encoding="utf-8")
            )
            names = [
                ln.partition(":")[2].strip()
                for ln in frontmatter.splitlines()
                if ln.startswith("name:")
            ]
            if names != [name]:
                findings.append(f"{name}: SKILL.md frontmatter name is {names!r}")
        references = skills_dir / name / "references"
        if references.exists() and not any(p.is_file() for p in references.rglob("*")):
            findings.append(f"{name}: an empty references/")
    for name in sorted(present - set(skills)):
        findings.append(f"{name}: a source directory no declaration names")
    return findings


class StackSkillSourcesTest(unittest.TestCase):
    """§S1.1 / §S1.2 / AC1 — ``generator/skills/`` holds exactly the skills
    ``generator/stack-skills.toml`` declares, each in a directory named as its ``SKILL.md``'s
    frontmatter ``name``. The checker is proved both ways on synthetic trees first."""

    def test_generator_skills_hold_exactly_the_declared_skills(self):
        good = {
            "alpha-stack": FIXTURE_SOURCES["alpha-stack"],
            "ghost-stack": FIXTURE_SOURCES["ghost-stack"],
        }
        good_decl = {name: FIXTURE_DECLARATION[name] for name in good}
        cases = {
            "clean": (good_decl, good, []),
            "undeclared source": (
                {"alpha-stack": ["rust"]},
                good,
                ["ghost-stack: a source directory no declaration names"],
            ),
            "declared, no source": (
                {**good_decl, "missing-stack": ["bun"]},
                good,
                ["missing-stack: declared with no source directory"],
            ),
            "no SKILL.md": (
                {**good_decl, "hollow-stack": ["arduino"]},
                {**good, "hollow-stack": FIXTURE_SOURCES["hollow-stack"]},
                ["hollow-stack: source has no SKILL.md"],
            ),
            "name mismatch": (
                {**good_decl, "gamma-stack": ["bun"]},
                {
                    **good,
                    "gamma-stack": {"SKILL.md": skill_md("delta-stack", "d", "b\n")},
                },
                ["gamma-stack: SKILL.md frontmatter name is ['delta-stack']"],
            ),
            "no stacks": (
                {**good_decl, "beta-stack": []},
                {
                    **good,
                    "beta-stack": {"SKILL.md": skill_md("beta-stack", "d", "b\n")},
                },
                ["beta-stack: declares no stacks"],
            ),
        }
        with tempfile.TemporaryDirectory(prefix="modelb-stack-skill-sources-") as tmp:
            for label, (declaration, sources, expected) in cases.items():
                with self.subTest(fixture=label):
                    generator_dir = Path(tmp) / label.replace(" ", "-") / "generator"
                    write_skill_sources(generator_dir, declaration, sources)
                    self.assertEqual(
                        stack_skill_source_findings(generator_dir), expected
                    )
            empty_refs = Path(tmp) / "empty-refs" / "generator"
            write_skill_sources(empty_refs, good_decl, good)
            (empty_refs / "skills" / "ghost-stack" / "references").mkdir()
            self.assertEqual(
                stack_skill_source_findings(empty_refs),
                ["ghost-stack: an empty references/"],
            )
            self.assertEqual(
                stack_skill_source_findings(Path(tmp) / "absent"),
                ["no declaration file stack-skills.toml"],
            )
        self.assertEqual(
            stack_skill_source_findings(GENERATOR_DIR),
            [],
            "§S1.1/§S1.2/AC1: the repository's generator/skills/ and "
            "generator/stack-skills.toml",
        )


