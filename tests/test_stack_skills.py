class InitRendersStackSkillsTest(_StackSkillSandbox):
    """§S1.3 / AC1 — ``init --stacks rust`` renders ``alpha-stack``, the skill declared for rust,
    into ``.agents/skills/alpha-stack/`` with the two pinned markers; the files are emitted and
    committed."""

    def setUp(self):
        super().setUp()
        self.target = self.root / "proj"
        self.axi = self.init_ok(self.target, "rust", no_commit=False)

    def test_init_renders_exactly_the_declared_skill_of_each_listed_stack(self):
        self.assert_rendered(self.target, ["rust"], "§S1.3/AC1")
        self.assertFalse(
            (self.target / SKILLS_RELDIR / "ghost-stack").exists(),
            "§S1.3: a skill declared for a stack not in --stacks is not rendered",
        )

    def test_rendered_skill_md_carries_the_frontmatter_marker_over_its_source(self):
        path = self.target / ALPHA_SKILL
        self.assertTrue(path.is_file(), f"§S1.3/AC1: {ALPHA_SKILL} must be rendered")
        text = path.read_text(encoding="utf-8")
        frontmatter, _body = split_frontmatter(text)
        markers = [
            ln for ln in frontmatter.splitlines() if ln.startswith(SKILL_MARKER_PREFIX)
        ]
        self.assertEqual(
            len(markers),
            1,
            f"§S1.3: exactly one frontmatter marker in SKILL.md; got {text!r}",
        )
        digest = markers[0][len(SKILL_MARKER_PREFIX) :]
        self.assertRegex(digest, HEX64, "§S1.3: the marker carries a bare sha256")
        without = text.replace(markers[0] + "\n", "", 1)
        self.assertEqual(
            without,
            FIXTURE_SOURCES["alpha-stack"]["SKILL.md"],
            "§S1.3: SKILL.md renders its source; only the marker line is added",
        )
        self.assertEqual(
            digest,
            sha256_text(without),
            "§S1.3: the marker's sha256 is the file's without the marker line (the agents' rule)",
        )

    def test_each_rendered_reference_carries_the_first_line_marker_over_its_source(
        self,
    ):
        for ref in ("references/alpha-notes.md", "references/beta-notes.md"):
            with self.subTest(reference=ref):
                path = self.target / rel("alpha-stack", ref)
                self.assertTrue(path.is_file(), f"§S1.3/AC1: {path} must be rendered")
                first, _, rest = path.read_text(encoding="utf-8").partition("\n")
                self.assertEqual(
                    rest,
                    FIXTURE_SOURCES["alpha-stack"][ref],
                    "§S1.3: a reference renders its source under one marker line",
                )
                self.assertEqual(
                    first,
                    f"{REFERENCE_MARKER_PREFIX}{sha256_text(rest)}{REFERENCE_MARKER_SUFFIX}",
                    "§S1.3: the first line is the reference marker over the rest of the file",
                )

    def test_rendered_files_join_the_emitted_list_and_the_commit(self):
        emitted = _listed(self.axi, "emitted")
        tracked = repo_git(self.target, "ls-files").splitlines()
        for path in expected_skill_files(["rust"]):
            with self.subTest(path=path):
                self.assertEqual(
                    emitted.count(path),
                    1,
                    f"§S1.3: {path} is listed once in init's emitted files; "
                    f"emitted={emitted!r}",
                )
                self.assertIn(path, tracked, "§S1.3: the rendered files are tracked")


