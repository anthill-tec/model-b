class _StackSkillSandbox(unittest.TestCase):
    """Per-test sandbox: ``HOME``, a provisioned Pi agent dir, ``MODELB_HOME`` (its
    ``install.toml`` naming the private asset root and a hook-script store),
    ``XDG_DATA_HOME``; ``init`` and ``agents`` run in process against it."""

    def setUp(self):
        self.root = Path(tempfile.mkdtemp(prefix="modelb-stack-skills-")).resolve()
        self.addCleanup(shutil.rmtree, self.root, ignore_errors=True)
        self.home = make_home(self.root / "home", crucible_manifest=False)
        self.agent_dir = make_provisioned_agent_dir(self.root / "agent")
        self.xdg = self.root / "xdg"
        self.xdg.mkdir()
        self.asset_root = build_asset_root(self.root / "assets")
        self.modelb_home = self.root / "modelb-home"
        hooks_scripts_dir = deploy_hook_scripts(
            self.modelb_home / ".agents" / "hooks" / "scripts"
        )
        (self.modelb_home / "install.toml").write_text(
            "[install]\n"
            'version = "0.1.0"\n'
            'harnesses = ["pi"]\n'
            f'asset_root = "{self.asset_root}"\n'
            f'hooks_scripts_dir = "{hooks_scripts_dir}"\n'
            '\n[deps]\nuv = "present"\n'
            '\n[capabilities]\n"lean-ctx" = "detected"\n'
            "\n[files]\n",
            encoding="utf-8",
        )

    def _environ(self):
        return mock.patch.dict(
            os.environ,
            {
                "HOME": str(self.home),
                AGENT_DIR_ENV: str(self.agent_dir),
                "MODELB_HOME": str(self.modelb_home),
                "XDG_DATA_HOME": str(self.xdg),
            },
        )

    def init(self, target: Path, stacks: str, **fields):
        """``scaffold.run_init`` in process; returns ``(rc, axi, stderr)``."""
        args = argparse.Namespace(
            name="X",
            token="xproj",
            acronym="XP",
            mode="solo",
            repo_shape="standalone",
            stacks=stacks,
            owner="tester",
            target=str(target),
            dry_run=False,
            no_commit=True,
            register=False,
            force_managed=False,
        )
        for key, value in fields.items():
            setattr(args, key, value)
        out, err = io.StringIO(), io.StringIO()
        with (
            self._environ(),
            contextlib.redirect_stdout(out),
            contextlib.redirect_stderr(err),
        ):
            rc = scaffold.run_init(args, self.modelb_home)
        return rc, decode_axi(out.getvalue()), err.getvalue()

    def init_ok(self, target: Path, stacks: str, **fields):
        rc, axi, err = self.init(target, stacks, **fields)
        self.assertEqual(
            rc, 0, f"precondition: init must succeed; axi={axi!r} stderr={err!r}"
        )
        return axi

    def agents(self, project: Path, stacks: str | None = None):
        """``scaffold.run_agents`` in process from ``project``'s root; ``(rc, axi, stderr)``."""
        args = argparse.Namespace(stacks=stacks, force_managed=False)
        out, err = io.StringIO(), io.StringIO()
        with (
            self._environ(),
            contextlib.redirect_stdout(out),
            contextlib.redirect_stderr(err),
        ):
            rc = scaffold.run_agents(args, self.modelb_home, project_root=project)
        return rc, decode_axi(out.getvalue()), err.getvalue()

    def agents_ok(self, project: Path, stacks: str | None = None) -> dict:
        rc, axi, err = self.agents(project, stacks)
        self.assertEqual(
            rc, 0, f"`modelb-axi agents` must succeed; axi={axi!r} stderr={err!r}"
        )
        return axi

    def source(self, name: str, path: str) -> Path:
        return self.asset_root / "generator" / "skills" / name / path

    def assert_rendered(self, project: Path, stacks: list[str], why: str) -> None:
        self.assertEqual(
            skill_files(project),
            expected_skill_files(stacks),
            f"{why}: .agents/skills must hold exactly the declared skills of {stacks}",
        )


def _listed(axi: dict, key: str) -> list[str]:
    return [str(item) for item in axi.get(key) or []]


