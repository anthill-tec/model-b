REPO_ROOT = Path(__file__).resolve().parent.parent
GENERATOR_DIR = REPO_ROOT / "generator"

#: §S1.3 — the frontmatter marker of a rendered ``SKILL.md`` (the sha256 follows).
SKILL_MARKER_PREFIX = "# generated by modelb-axi (Model B stack skills); sha256 "
#: §S1.3 — the first-line marker of a rendered reference: prefix, sha256, suffix.
REFERENCE_MARKER_PREFIX = "<!-- generated by modelb-axi (Model B stack skills); sha256 "
REFERENCE_MARKER_SUFFIX = " -->"
#: §S1.3 — where a project's stack skills render, relative to its root.
SKILLS_RELDIR = ".agents/skills"
HEX64 = re.compile(r"[0-9a-f]{64}")


# ------------------------------------------------------------------ fixture data ----


def skill_md(name: str, description: str, body: str) -> str:
    """A skill source's ``SKILL.md``: frontmatter ``name`` and ``description``, then ``body``."""
    return f"---\nname: {name}\ndescription: {description}\n---\n\n{body}"


#: Synthetic declaration: skill name -> the stacks it renders for.
FIXTURE_DECLARATION = {
    "alpha-stack": ["rust"],
    "ghost-stack": ["java"],
    "hollow-stack": ["arduino"],
}

#: Synthetic sources: skill name -> {path relative to the skill's source dir: text}.
FIXTURE_SOURCES = {
    "alpha-stack": {
        "SKILL.md": skill_md(
            "alpha-stack",
            "Synthetic stack skill for the rust stack: fixture material only.",
            "# Alpha stack\n\nRead [the alpha notes](references/alpha-notes.md) when a task "
            "needs them, and [the beta notes](references/beta-notes.md).\n",
        ),
        "references/alpha-notes.md": "# Alpha notes\n\nThe first synthetic reference.\n",
        "references/beta-notes.md": "# Beta notes\n\nThe second synthetic reference.\n",
    },
    "ghost-stack": {
        "SKILL.md": skill_md(
            "ghost-stack",
            "Synthetic stack skill for a stack with no stack file: fixture material only.",
            "# Ghost stack\n\nNo references.\n",
        ),
    },
    # Declared, but its source has no SKILL.md: it renders nothing (§S1.2).
    "hollow-stack": {
        "references/orphan.md": "# Orphan\n\nA reference with no SKILL.md beside it.\n",
    },
}


def declaration_text(declaration: dict) -> str:
    """``generator/stack-skills.toml`` for ``declaration`` (skill name -> stacks): one
    ``[skills.<name>]`` table per skill carrying ``stacks`` — the one place the shape is written."""
    out = []
    for name, stacks in declaration.items():
        out.append(f"[skills.{name}]")
        out.append("stacks = [" + ", ".join(f'"{s}"' for s in stacks) + "]")
        out.append("")
    return "\n".join(out)


def write_skill_sources(generator_dir: Path, declaration: dict, sources: dict) -> None:
    """Write the declaration file and every skill source under ``generator_dir``."""
    generator_dir.mkdir(parents=True, exist_ok=True)
    (generator_dir / "stack-skills.toml").write_text(
        declaration_text(declaration), encoding="utf-8"
    )
    for name, files in sources.items():
        for rel, text in files.items():
            path = generator_dir / "skills" / name / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")


def build_asset_root(dest: Path) -> Path:
    """A private asset root: the repository's agent templates and stack files, its memory
    templates, and the SYNTHETIC skill declaration and sources (never the real ones)."""
    shutil.copytree(GENERATOR_DIR / "templates", dest / "generator" / "templates")
    shutil.copytree(GENERATOR_DIR / "stacks", dest / "generator" / "stacks")
    shutil.copytree(
        REPO_ROOT / "skills-src" / "memory-templates",
        dest / "skills-src" / "memory-templates",
    )
    write_skill_sources(dest / "generator", FIXTURE_DECLARATION, FIXTURE_SOURCES)
    return dest


def expected_skill_files(stacks: list[str]) -> list[str]:
    """The project-relative files a render for ``stacks`` writes, derived from the fixture data:
    every file of each declared skill naming one of ``stacks`` whose source has a SKILL.md."""
    out = []
    for name, declared in FIXTURE_DECLARATION.items():
        files = FIXTURE_SOURCES.get(name, {})
        if set(declared) & set(stacks) and "SKILL.md" in files:
            out.extend(f"{SKILLS_RELDIR}/{name}/{rel}" for rel in files)
    return sorted(out)


def skill_files(project: Path) -> list[str]:
    """Every file under ``<project>/.agents/skills``, project-relative (posix), sorted."""
    root = project / SKILLS_RELDIR
    if not root.is_dir():
        return []
    return sorted(
        p.relative_to(project).as_posix() for p in root.rglob("*") if p.is_file()
    )


def snapshot(project: Path, rels) -> dict:
    """``{rel: bytes}`` of each of ``rels`` that exists under ``project``."""
    return {
        rel: (project / rel).read_bytes() for rel in rels if (project / rel).is_file()
    }


def with_skill_marker(text: str, digest: str) -> str:
    """``text`` (a SKILL.md) with the §S1.3 frontmatter marker carrying ``digest`` inserted as
    its first frontmatter line."""
    head, _, rest = text.partition("\n")
    return f"{head}\n{SKILL_MARKER_PREFIX}{digest}\n{rest}"


def rel(name: str, path: str) -> str:
    """The project-relative path of ``path`` within the rendered skill ``name``."""
    return f"{SKILLS_RELDIR}/{name}/{path}"


ALPHA_SKILL = rel("alpha-stack", "SKILL.md")
ALPHA_NOTES = rel("alpha-stack", "references/alpha-notes.md")
BETA_NOTES = rel("alpha-stack", "references/beta-notes.md")


