"""The project's lean-ctx config, ``.lean-ctx.toml`` (PRD D5; CR-MDB-091 §S1).

- :func:`render_config` renders the file: its FIRST line is the CR-MDB-025 §S6
  ownership marker as a TOML comment (the prefix plus the sha256 of the body),
  then the body — the two knowledge levers PRD D5 rules (2026-10-29), and no
  other key or comment. The render takes no argument: it depends on no stack,
  harness, lean-ctx verdict or ``HOME``.
- :func:`place_project_config` writes it at the project root under the §S6
  ownership rules (:func:`modelb_axi.agents.place_owned`), the way the
  permission policy is placed (``DN-multi-harness-deploy-model §D17``).

Model B never runs a lean-ctx command (``trust``, ``config set``,
``index build``, ``doctor --fix``): this module writes one file, through
``agents.place_owned``, and runs no process. Without lean-ctx the file is inert.

Stdlib only.
"""

from pathlib import Path

from modelb_axi import agents

#: The config file, relative to the project root.
CONFIG_RELPATH = ".lean-ctx.toml"

#: The ownership marker line, minus its sha256 hex (CR-MDB-025 §S6).
MARKER_PREFIX = "# generated by modelb-axi (Model B lean-ctx project config); sha256 "

#: The body, exactly as §S1 rules it, ending with one newline.
_BODY = "[memory.knowledge]\nmax_facts = 500\n\n[autonomy]\nauto_consolidate = false\n"


def render_config() -> str:
    """The config text: the marker line over the body, then the body."""
    return f"{MARKER_PREFIX}{agents.sha256_text(_BODY)}\n{_BODY}"


def ownership_state(text: str) -> str:
    """Classify an existing config: ``intact``, ``hand_modified`` or
    ``unmanaged``. Delegates to :func:`modelb_axi.agents.first_line_ownership`,
    looked up on ``agents`` at call time (CR-MDB-068 §S2)."""
    return agents.first_line_ownership(text, MARKER_PREFIX)


def place_project_config(
    project_root: Path, *, force_managed: bool = False, report: dict | None = None,
) -> dict:
    """Write the config at ``project_root`` under the §S6 ownership rules;
    returns (and fills, when given) ``report`` with ``written`` /
    ``unchanged`` / ``skipped`` / ``unmanaged`` project-relative paths."""
    if report is None:
        report = {}
    for key in ("written", "unchanged", "skipped", "unmanaged"):
        report.setdefault(key, [])
    rel = CONFIG_RELPATH
    agents.place_owned(
        project_root / rel, rel, render_config(), force_managed, report,
        classify=ownership_state,
    )
    return report
