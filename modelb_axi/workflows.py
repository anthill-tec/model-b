"""Render a project's release workflow and its two scripts (CR-MDB-068 §S2/§S4).

:func:`render` reads the workflow's parts and the two scripts from ``source_dir`` — the
``workflows-src`` asset root, resolved by ``scaffold._workflow_sources`` — and returns, keyed by
project-relative path, ``.github/workflows/release.yml``, ``.github/scripts/stamp_version.py``
and ``.github/scripts/changelog_section.py``. Each text's first line is the ownership marker
:data:`MARKER_PREFIX` plus the sha256 of the rest, so ``agents.first_line_ownership`` classifies
it and ``agents.place_owned`` writes it.

The parts under ``source_dir/release/`` are YAML fragments with ``@@NAME@@`` placeholders: one
standing alone on its line is a block, replaced by lines (or by nothing); one inside a line is
replaced inline; ``@@USES:<owner>/<repo>@@`` is the action's pinned reference from
:data:`ACTION_PINS`. Rendering is deterministic and reads nothing outside ``source_dir``.

Stdlib only.
"""

import re
from pathlib import Path, PurePosixPath

from modelb_axi import agents

#: The ownership marker line, minus its sha256 hex (§S2).
MARKER_PREFIX = "# generated by modelb-axi (Model B release workflow); sha256 "

#: Every action a rendered workflow uses: its 40-hex commit SHA and its release tag (§S2).
#: ``oven-sh/setup-bun`` and ``actions/setup-java`` measured 2026-10-14 with ``git ls-remote``
#: (both lightweight tags: the ref is the commit).
ACTION_PINS: dict[str, tuple[str, str]] = {
    "actions/checkout": ("11d5960a326750d5838078e36cf38b85af677262", "v4.4.0"),
    "actions/setup-python": ("5fda3b95a4ea91299a34e894583c3862153e4b97", "v7.0.0"),
    "astral-sh/setup-uv": ("d0cc045d04ccac9d8b7881df0226f9e82c39688e", "v6.8.0"),
    "pypa/gh-action-pypi-publish": ("dc37677b2e1c63e2034f94d8a5b11f265b73ba33", "v1.14.2"),
    "actions/setup-node": ("49933ea5288caeca8642d1e84afbd3f7d6820020", "v4.4.0"),
    "oven-sh/setup-bun": ("0c5077e51419868618aeaa5fe8019c62421857d6", "v2.2.0"),
    "actions/setup-java": ("de7274f081f381c8f8158605e0321c36c376e2e6", "v6.0.1"),
}

#: The rendered files, by project-relative path.
RELEASE_YML = ".github/workflows/release.yml"
STAMP_SCRIPT = ".github/scripts/stamp_version.py"
SECTION_SCRIPT = ".github/scripts/changelog_section.py"
#: The scripts' sources under ``source_dir``, by rendered path.
_SCRIPTS = {STAMP_SCRIPT: "stamp_version.py", SECTION_SCRIPT: "changelog_section.py"}

#: Each stack's test-job part and the job id it renders (§S4's table).
_TEST_PARTS = {"python": "test-python", "bun": "test-bun", "rust": "test-rust",
               "quarkus": "test-maven", "java": "test-maven", "arduino": "test-arduino"}
#: The release targets ``RELEASE_TARGETS`` may name, in canonical order (CR-MDB-068 §S1): the
#: one definition, which ``scaffold`` imports.
RELEASE_TARGETS: tuple[str, ...] = ("pypi", "npm", "github-assets")
#: The release targets that take a ``:<dir>`` and carry a version source (CR-MDB-068 §S1).
_VERSIONED = ("pypi", "npm")
#: A target ``dir`` the rendered workflow may write unquoted into a shell line (VERIFY F1).
_SAFE_DIR = re.compile(r"[A-Za-z0-9._/-]+")


def _read(source_dir: Path, name: str) -> str:
    return (source_dir / name).read_text(encoding="utf-8")


def _fill(text: str, values: dict[str, str]) -> str:
    """``text`` with each ``@@NAME@@`` placeholder replaced: a block one (alone on its line) by
    its value's lines, an inline one by its value; ``@@USES:<action>@@`` by the pinned
    reference. Raises ``ValueError`` naming any placeholder left unfilled."""
    for name, value in values.items():
        if text.startswith(f"@@{name}@@\n"):
            text = value + text[len(f"@@{name}@@\n"):]
        text = text.replace(f"\n@@{name}@@\n", f"\n{value}")
        text = text.replace(f"@@{name}@@", value)
    for action, (sha, version) in ACTION_PINS.items():
        text = text.replace(f"@@USES:{action}@@", f"{action}@{sha} # {version}")
    if "@@" in text:
        start = text.index("@@")
        raise ValueError(f"unfilled placeholder in a workflow part: {text[start:start + 40]!r}")
    return text


def parse_target(item: str) -> tuple[str, str]:
    """``(name, dir)`` of one ``name`` or ``name:dir`` release target, ``dir`` normalised as a
    :class:`PurePosixPath` (``.`` for none): the one target parser, called by ``scaffold``'s
    ``release_targets_csv`` rule and by :func:`render` (CR-MDB-068 §S1). Raises ``ValueError``
    naming the bad part: an unknown name (listing the supported ones), a ``dir`` on a target that
    takes none, an empty or blank ``dir``, a ``dir`` holding a character outside
    ``[A-Za-z0-9._/-]`` (the workflow writes it unquoted into a shell line), and an absolute
    ``dir`` or one holding ``..``."""
    name, sep, raw = item.partition(":")
    if name not in RELEASE_TARGETS:
        raise ValueError(f"names an unknown release target {name!r}; "
                         f"supported: {', '.join(RELEASE_TARGETS)}")
    if not sep:
        return name, "."
    if name not in _VERSIONED:
        raise ValueError(f"gives a dir to {name}, which takes none")
    directory = raw.strip()
    if not directory:
        raise ValueError(f"gives {name} an empty dir")
    if not _SAFE_DIR.fullmatch(directory):
        raise ValueError(f"gives {name} the dir {directory!r}, which may hold only the "
                         "characters [A-Za-z0-9._/-]")
    path = PurePosixPath(directory)
    if path.is_absolute() or ".." in path.parts:
        raise ValueError(f"gives {name} the dir {directory!r}, which must be relative "
                         "and hold no `..`")
    return name, str(path)


def _parsed_targets(targets: list[str]) -> list[tuple[str, str]]:
    """``(name, dir)`` of each target, each parsed once by :func:`parse_target`, in canonical
    order; raises ``ValueError`` naming a duplicate."""
    parsed: dict[str, str] = {}
    for target in targets:
        name, directory = parse_target(target)
        if name in parsed:
            raise ValueError(f"names the release target {name} twice (a duplicate)")
        parsed[name] = directory
    return [(name, parsed[name]) for name in RELEASE_TARGETS if name in parsed]


def _workdir(directory: str, indent: int = 8) -> str:
    return "" if directory == "." else f"{' ' * indent}working-directory: {directory}\n"


def _setup(source_dir: Path, names: list[str]) -> str:
    """The header's one-time setup list: ``RELEASE_PAT``, then each rendered target's needs;
    each item ends with ``;``, the last with ``.``."""
    text = "".join(_read(source_dir, f"release/setup-{name}.yml")
                   for name in ("release-pat", *names))
    return text[:-2] + ".\n" if text.endswith(";\n") else text


def _test_jobs(source_dir: Path, stacks: list[str]) -> list[str]:
    jobs = []
    for stack in stacks:
        part = _TEST_PARTS.get(stack)
        if part is None:
            raise ValueError(f"stack {stack!r} has no release-workflow test job; "
                             f"known: {', '.join(_TEST_PARTS)}")
        jobs.append(_fill(_read(source_dir, f"release/{part}.yml"), {"STACK": stack}))
    return jobs


def _rehearse_steps(source_dir: Path, parsed: list[tuple[str, str]], build: str) -> str:
    steps = []
    for name, directory in parsed:
        values = {"WORKDIR": _workdir(directory), "BUILD_ASSETS": build,
                  "PACKAGES_DIR": ("" if directory == "."
                                   else f"          packages-dir: {directory}/dist\n"),
                  "COPY": ("" if directory == "." else _fill(
                      _read(source_dir, "release/rehearse-npm-copy.yml"), {"DIR": directory}))}
        steps.append(_fill(_read(source_dir, f"release/rehearse-{name}.yml"), values))
    return "".join(steps)


def _publish_jobs(source_dir: Path, parsed: list[tuple[str, str]], needs: str,
                  build: str) -> list[str]:
    guard = _fill(_read(source_dir, "release/guard.yml"), {})
    jobs = []
    for name, directory in parsed:
        values = {"NEEDS": needs, "GUARD": guard, "BUILD_ASSETS": build,
                  "WORKDIR": _workdir(directory),
                  "PACKAGES_DIR": ("" if directory == "." else
                                   f"        with:\n          packages-dir: {directory}/dist\n"),
                  "DEFAULTS": ("" if directory == "." else
                               f"    defaults:\n      run:\n{_workdir(directory)}"),
                  "COPY": ("" if directory == "."
                           else _read(source_dir, "release/publish-npm-copy.yml"))}
        jobs.append(_fill(_read(source_dir, f"release/publish-{name}.yml"), values))
    return jobs


def _release_yml(stacks: list[str], targets: list[str], source_dir: Path) -> str:
    parsed = _parsed_targets(targets)
    names = [name for name, _directory in parsed]
    needs = ", ".join(f"test-{stack}" for stack in stacks)
    versioned = "".join(f" {name}:{directory}" for name, directory in parsed
                        if name in _VERSIONED)
    build = _read(source_dir, "release/build-assets.yml")
    header = _fill(_read(source_dir, "release/header.yml"), {
        "PUBLISHES": " and the guarded publishes" if parsed else "",
        "SETUP": _setup(source_dir, names)})
    check = (_fill(_read(source_dir, "release/create-release-check.yml"),
                   {"VERSIONED": versioned}) if versioned else "")
    create = _fill(_read(source_dir, "release/create-release.yml"),
                   {"NEEDS": needs, "CHECK": check})
    pypi = "pypi" in names
    rehearse = _fill(_read(source_dir, "release/rehearse.yml"), {
        "NEEDS": needs, "VERSIONED": versioned,
        "ENVIRONMENT": "    environment: testpypi\n" if pypi else "",
        "ID_TOKEN": "      id-token: write\n" if pypi else "",
        "TARGET_STEPS": _rehearse_steps(source_dir, parsed, build)})
    jobs = [*_test_jobs(source_dir, stacks), create, rehearse,
            *_publish_jobs(source_dir, parsed, needs, build)]
    return header + "\n".join(jobs)


def _with_marker(body: str) -> str:
    return f"{MARKER_PREFIX}{agents._sha256_text(body)}\n{body}"


def ownership_state(text: str) -> str:
    """Classify an existing release file by its first-line marker (CR-MDB-068 §S2): delegates to
    :func:`modelb_axi.agents.first_line_ownership` with :data:`MARKER_PREFIX`; the ``classify`` of
    ``agents.place_owned`` for the three rendered files."""
    return agents.first_line_ownership(text, MARKER_PREFIX)


def render(stacks: list[str], targets: list[str], source_dir: Path) -> dict[str, str]:
    """The three release files for ``stacks`` and the canonical ``targets`` (CR-MDB-068 §S2),
    keyed by project-relative path, each under its ownership marker. Deterministic; reads
    ``source_dir`` only. Raises ``OSError`` when a part or script is missing there and
    ``ValueError`` for an unknown stack or target."""
    source_dir = Path(source_dir)
    if not stacks:
        raise ValueError("the release workflow needs at least one stack")
    files = {RELEASE_YML: _with_marker(_release_yml(list(stacks), list(targets), source_dir))}
    for rel, name in _SCRIPTS.items():
        files[rel] = _with_marker(_read(source_dir, name))
    return files
