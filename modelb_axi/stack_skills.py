"""Stack skills: declaration, sources and rendering (CR-MDB-085 §S1).

A stack skill's source is ``generator/skills/<name>/`` — a ``SKILL.md`` and, only when the
skill has references, a ``references/`` directory (§S1.1). One declaration file,
``generator/stack-skills.toml``, names the stacks each skill renders for: one
``[skills.<name>]`` table per skill carrying ``stacks = ["<stack>", …]``; a missing file or a
missing ``[skills]`` table declares no skill, and a stack with or without a stack file may be
named (§S1.2). Sources resolve from the ``generator/`` directory of the asset root the agent
sources resolve from.

:func:`render_skills` renders, in memory and before any write, every file of each declared
skill of the project's stacks whose source has a ``SKILL.md`` (a declared skill without one
renders nothing). Each rendered file carries a marker (§S1.3): ``SKILL.md`` the frontmatter
marker :data:`SKILL_MARKER_PREFIX`, each reference the first-line marker
:data:`REFERENCE_MARKER_PREFIX` … :data:`REFERENCE_MARKER_SUFFIX`. :func:`place_skills` writes
them at the project root under the agent definitions' ownership rules
(``agents.place_owned``): it never deletes.

Stdlib only.
"""

import tomllib
from functools import partial
from pathlib import Path

from modelb_axi import agents

#: §S1.2 — the declaration file, beside ``generator/stacks/``.
DECLARATION_NAME = "stack-skills.toml"
#: §S1.1 — the sources' directory under ``generator/``.
SOURCES_DIRNAME = "skills"
#: §S1.3 — where a project's stack skills render, relative to its root.
PROJECT_SKILLS_RELDIR = Path(".agents") / "skills"
SKILL_FILE = "SKILL.md"
REFERENCES_DIRNAME = "references"

#: §S1.3 — the frontmatter marker of a rendered ``SKILL.md``; the sha256 follows.
SKILL_MARKER_PREFIX = "# generated by modelb-axi (Model B stack skills); sha256 "
#: §S1.3 — the first-line marker of a rendered reference: prefix, sha256, suffix.
REFERENCE_MARKER_PREFIX = "<!-- generated by modelb-axi (Model B stack skills); sha256 "
REFERENCE_MARKER_SUFFIX = " -->"


class StackSkillError(ValueError):
    """The stack-skill declaration or a declared skill's source cannot be rendered."""


def load_declaration(generator_dir: Path) -> dict[str, list[str]]:
    """Skill name -> the stacks it renders for, in declaration order, from
    ``<generator_dir>/stack-skills.toml``. A missing file or ``[skills]`` table declares no
    skill; an unreadable or malformed one raises :class:`StackSkillError`."""
    path = generator_dir / DECLARATION_NAME
    if not path.is_file():
        return {}
    try:
        with path.open("rb") as fh:
            data = tomllib.load(fh)
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise StackSkillError(
            f"{path} cannot be read: {type(exc).__name__}: {exc}"
        ) from exc
    skills = data.get("skills", {})
    if not isinstance(skills, dict):
        raise StackSkillError(f"{path}: [skills] is not a table")
    declaration: dict[str, list[str]] = {}
    for name, entry in skills.items():
        stacks = entry.get("stacks") if isinstance(entry, dict) else None
        if not (
            isinstance(stacks, list)
            and stacks
            and all(isinstance(s, str) for s in stacks)
        ):
            raise StackSkillError(f"{path}: skill {name!r} declares no stacks")
        declaration[name] = list(stacks)
    return declaration


def skills_for(
    declaration: dict[str, list[str]], stacks: list[str]
) -> dict[str, list[str]]:
    """Each stack of ``stacks`` -> the declared skills naming it, in declaration order."""
    return {
        stack: [name for name, declared in declaration.items() if stack in declared]
        for stack in stacks
    }


def _reference_marker(text: str) -> str:
    """``text`` under the §S1.3 first-line reference marker over it."""
    return f"{REFERENCE_MARKER_PREFIX}{agents.sha256_text(text)}{REFERENCE_MARKER_SUFFIX}\n{text}"


def _frontmatter_name(text: str) -> str | None:
    """The ``name`` a ``SKILL.md``'s frontmatter declares (quotes stripped), or ``None`` when
    its frontmatter declares none."""
    for line in text.splitlines()[1:]:
        if line.rstrip() == "---":
            break
        key, sep, value = line.partition(":")
        if sep and key.strip() == "name":
            return value.strip().strip("\"'")
    return None


def render_skills(generator_dir: Path, stacks: list[str]) -> dict[str, str]:
    """Every file of the declared skills of ``stacks``, rendered in memory with its marker and
    keyed by project-relative (posix) path; writes nothing. A declared skill whose source has
    no ``SKILL.md`` renders nothing. Raises :class:`StackSkillError` when the declaration or a
    source cannot be read, a ``SKILL.md`` has no frontmatter to carry its marker, or its
    frontmatter ``name`` differs from its source directory (§S1.1)."""
    declaration = load_declaration(generator_dir)
    rendered: dict[str, str] = {}
    for name, declared in declaration.items():
        if not set(declared) & set(stacks):
            continue
        source = generator_dir / SOURCES_DIRNAME / name
        skill_md = source / SKILL_FILE
        if not skill_md.is_file():
            continue
        reldir = PROJECT_SKILLS_RELDIR / name
        try:
            text = skill_md.read_text(encoding="utf-8")
            if not text.startswith("---\n"):
                raise StackSkillError(f"{skill_md}: no frontmatter to carry the marker")
            declared_name = _frontmatter_name(text)
            if declared_name != name:
                raise StackSkillError(
                    f"the stack skill {name!r}: {skill_md} declares the frontmatter name "
                    f"{declared_name!r}, not its directory's {name!r}"
                )
            rendered[(reldir / SKILL_FILE).as_posix()] = agents.with_marker(
                text, SKILL_MARKER_PREFIX
            )
            references = source / REFERENCES_DIRNAME
            if references.is_dir():
                for ref in sorted(p for p in references.rglob("*") if p.is_file()):
                    rel = reldir / ref.relative_to(source)
                    rendered[rel.as_posix()] = _reference_marker(
                        ref.read_text(encoding="utf-8")
                    )
        except (OSError, UnicodeDecodeError) as exc:
            raise StackSkillError(
                f"the stack skill {name!r} cannot be rendered: {type(exc).__name__}: {exc}"
            ) from exc
    return rendered


def ownership_state(rel: str, text: str) -> str:
    """Classify an existing rendered file by the marker its kind carries (§S1.3)."""
    if (
        Path(rel).name == SKILL_FILE
        and Path(rel).parent.parent == PROJECT_SKILLS_RELDIR
    ):
        return agents.ownership_state(text, SKILL_MARKER_PREFIX)
    return agents.first_line_ownership(
        text, REFERENCE_MARKER_PREFIX, REFERENCE_MARKER_SUFFIX
    )


def place_skills(
    project_root: Path, rendered: dict[str, str], force_managed: bool, report: dict
) -> dict:
    """Write the pre-rendered stack-skill files under ``project_root`` by the agent
    definitions' ownership rules (``agents.place_owned``): a missing file is written, an intact
    one rewritten, a hand-modified one skipped (unless ``force_managed``), an unmarked one never
    written; nothing is deleted. Fills and returns ``report`` (``written`` / ``unchanged`` /
    ``skipped`` / ``unmanaged``)."""
    for key in ("written", "unchanged", "skipped", "unmanaged"):
        report.setdefault(key, [])
    for rel, text in rendered.items():
        agents.place_owned(
            project_root / rel,
            rel,
            text,
            force_managed,
            report,
            classify=partial(ownership_state, rel),
        )
    return report
